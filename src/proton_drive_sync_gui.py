from gi.repository import Adw, Gio, GLib, Gtk  # noqa: E402

APP_ID = "io.github.protondrivesync.Settings"
STORES = [("keychain", "Schlüsselbund (GNOME Keyring, KWallet)"), ("pass", "pass (password-store)")]
DEFAULTS = {"debounce": 5, "remotePoll": 60, "maxDeletes": 50, "exclude": [".git", "node_modules"],
            "trayIcon": True}


def has_display() -> bool:
    return bool(os.environ.get("WAYLAND_DISPLAY") or os.environ.get("DISPLAY"))


def is_managed(path: Path) -> bool:
    """Config generated by Home Manager (symlink into the Nix store)?"""
    try:
        return path.is_symlink() and str(path.resolve()).startswith("/nix/store/")
    except OSError:
        return False


def split_list(text: str) -> list[str]:
    return [p.strip() for p in text.split(",") if p.strip()]


def run_async(fn, done):
    """Run fn() in a thread and call done(result, error) on the GTK main loop."""
    def worker():
        try:
            res, err = fn(), None
        except Exception as e:  # noqa: BLE001
            res, err = None, e
        GLib.idle_add(lambda: (done(res, err), False)[1])
    threading.Thread(target=worker, daemon=True).start()


class ProtonCli:
    def __init__(self, binary: str):
        self.binary = binary
        self.store: str | None = None

    def env(self):
        env = dict(os.environ)
        if self.store:
            env["PROTON_DRIVE_CREDENTIALS_STORE"] = self.store
        return env

    def logged_in(self) -> bool:
        p = subprocess.run([self.binary, "filesystem", "list", "/", "--json"],
                           capture_output=True, text=True, env=self.env(), stdin=subprocess.DEVNULL)
        return p.returncode == 0

    def list_folders(self, path: str) -> list[str]:
        cli = "/my-files" + ("" if path == "/" else path)
        p = subprocess.run([self.binary, "filesystem", "list", cli, "--json"],
                           capture_output=True, text=True, env=self.env(), stdin=subprocess.DEVNULL)
        if p.returncode != 0:
            raise RuntimeError((p.stderr or p.stdout).strip().splitlines()[-1] if (p.stderr or p.stdout).strip()
                               else "Abfrage fehlgeschlagen")
        names = []
        for item in json.loads(p.stdout or "[]"):
            name = item.get("name")
            if isinstance(name, dict):
                name = name.get("value") if name.get("ok") else None
            if name and item.get("type") == "folder" and not item.get("trashTime"):
                names.append(name)
        return sorted(names, key=str.lower)


