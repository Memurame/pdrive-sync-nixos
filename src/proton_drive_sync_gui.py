class FolderRow(Adw.ExpanderRow):
    def __init__(self, win: "Wizard", data: dict):
        super().__init__()
        self.win = win
        self.name = Adw.EntryRow(title="Name (eindeutig)")
        self.local = Adw.ActionRow(title="Lokaler Ordner", subtitle_selectable=True)
        pick_local = Gtk.Button(label="Wählen …", valign=Gtk.Align.CENTER,
                                tooltip_text="Lokalen Ordner auswählen", css_classes=["flat"])
        pick_local.connect("clicked", self.pick_local)
        self.local.add_suffix(pick_local)
        self.remote = Adw.EntryRow(title="Ordner in Proton Drive")
        pick_remote = Gtk.Button(label="Durchsuchen …", valign=Gtk.Align.CENTER,
                                 tooltip_text="Ordner in Proton Drive auswählen", css_classes=["flat"])
        pick_remote.connect("clicked", self.pick_remote)
        self.remote.add_suffix(pick_remote)
        self.exclude = Adw.EntryRow(title="Zusätzliche Ausnahmen (kommagetrennt, z. B. *.tmp, Cache)")
        remove = Adw.ButtonRow(title="Ordner entfernen", css_classes=["destructive-action"])
        remove.connect("activated", lambda *_: self.win.remove_folder(self))
        for r in (self.name, self.local, self.remote, self.exclude, remove):
            self.add_row(r)

        self.local_path = data.get("local", "")
        self.name.set_text(data.get("name", ""))
        self.remote.set_text(data.get("remote", ""))
        self.exclude.set_text(", ".join(data.get("exclude", [])))
        for e in (self.name, self.remote):
            e.connect("changed", lambda *_: self.refresh())
        self.refresh()

    def refresh(self):
        self.local.set_subtitle(self.local_path or "nicht gewählt")
        self.set_title(GLib.markup_escape_text(self.name.get_text() or "Neuer Ordner"))
        self.set_subtitle(GLib.markup_escape_text(
            f"{self.local_path or '…'}  ⇄  Proton:{self.remote.get_text() or '…'}"))

    def pick_local(self, *_):
        dlg = Gtk.FileDialog(title="Lokalen Ordner wählen")
        if self.local_path:
            dlg.set_initial_folder(Gio.File.new_for_path(os.path.expanduser(self.local_path)))

        def done(d, res):
            try:
                f = d.select_folder_finish(res)
            except GLib.Error:
                return
            path = f.get_path()
            home = os.path.expanduser("~")
            self.local_path = "~" + path[len(home):] if path.startswith(home + "/") else path
            if not self.name.get_text():
                self.name.set_text(os.path.basename(path))
            if not self.remote.get_text():
                self.remote.set_text("/" + os.path.basename(path))
            self.refresh()
        dlg.select_folder(self.win, None, done)

    def pick_remote(self, *_):
        start = str(PurePosixPath(self.remote.get_text() or "/").parent) if self.remote.get_text() else "/"

        def picked(path):
            self.remote.set_text(path)
            if not self.name.get_text() and path != "/":
                self.name.set_text(PurePosixPath(path).name)
        RemotePicker(self.win.cli, start, picked).present(self.win)

    def to_dict(self) -> dict:
        return {"name": self.name.get_text().strip(), "local": self.local_path,
                "remote": "/" + self.remote.get_text().strip().strip("/"),
                "exclude": split_list(self.exclude.get_text())}


