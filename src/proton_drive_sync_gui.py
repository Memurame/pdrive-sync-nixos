class RemotePicker(Adw.Dialog):
    def __init__(self, cli: ProtonCli, start: str, on_pick):
        super().__init__(title="Ordner in Proton Drive", content_width=420, content_height=520)
        self.cli, self.on_pick = cli, on_pick
        self.path = start if start.startswith("/") else "/"

        tv = Adw.ToolbarView()
        header = Adw.HeaderBar()
        self.up_btn = Gtk.Button(icon_name="go-up-symbolic", tooltip_text="Übergeordneter Ordner")
        self.up_btn.connect("clicked", lambda *_: self.load(str(PurePosixPath(self.path).parent)))
        header.pack_start(self.up_btn)
        tv.add_top_bar(header)

        self.stack = Gtk.Stack()
        self.listbox = Gtk.ListBox(css_classes=["boxed-list"], selection_mode=Gtk.SelectionMode.NONE,
                                   margin_top=12, margin_bottom=12, margin_start=12, margin_end=12,
                                   valign=Gtk.Align.START)
        scroller = Gtk.ScrolledWindow(child=self.listbox, vexpand=True)
        self.stack.add_named(scroller, "list")
        self.stack.add_named(Adw.Spinner(halign=Gtk.Align.CENTER, valign=Gtk.Align.CENTER,
                                         width_request=32, height_request=32), "loading")
        self.error = Adw.StatusPage(icon_name="dialog-warning-symbolic", title="Konnte nicht laden")
        self.stack.add_named(self.error, "error")
        tv.set_content(self.stack)

        bottom = Gtk.Box(spacing=12, margin_top=12, margin_bottom=12, margin_start=12, margin_end=12)
        self.path_label = Gtk.Label(xalign=0, hexpand=True, ellipsize=3, css_classes=["dim-label"])
        choose = Gtk.Button(label="Diesen Ordner wählen", css_classes=["suggested-action", "pill"])
        choose.connect("clicked", self.choose)
        bottom.append(self.path_label)
        bottom.append(choose)
        tv.add_bottom_bar(bottom)
        self.set_child(tv)
        self.load(self.path)

    def load(self, path: str):
        self.path = path
        self.path_label.set_label(path)
        self.up_btn.set_sensitive(path != "/")
        self.stack.set_visible_child_name("loading")
        run_async(lambda: self.cli.list_folders(path), self.loaded)

    def loaded(self, names, err):
        if err:
            # the folder may not exist yet – fall back to its parent once
            if self.path != "/":
                self.error.set_description(str(err))
            self.stack.set_visible_child_name("error")
            return
        while (row := self.listbox.get_row_at_index(0)) is not None:
            self.listbox.remove(row)
        if not names:
            self.listbox.append(Adw.ActionRow(title="Keine Unterordner", sensitive=False))
        for name in names:
            row = Adw.ActionRow(title=name, activatable=True)
            row.add_prefix(Gtk.Image(icon_name="folder-symbolic"))
            row.add_suffix(Gtk.Image(icon_name="go-next-symbolic"))
            row.connect("activated", lambda _r, n=name: self.load(str(PurePosixPath(self.path) / n)))
            self.listbox.append(row)
        self.stack.set_visible_child_name("list")

    def choose(self, *_):
        self.on_pick(self.path)
        self.close()


