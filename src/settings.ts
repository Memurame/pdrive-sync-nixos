import { existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, renameSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { expandHome, rjoin, xdg } from './util';

export interface FolderConfig {
    /** Unique ID (letters, digits, space, . _ -) – also the state file name. */
    name: string;
    /** Local folder (absolute or with ~). */
    local: string;
    /** Folder in "My files" of Proton Drive ("/" = everything). */
    remote: string;
    exclude: string[];
}

export interface Settings {
    folders: FolderConfig[];
    /** Glob patterns (name or relative path) that are never synced. */
    exclude: string[];
    /** Safety limit: a run that would delete more items per folder is aborted. */
    maxDeletes: number;
    /** Seconds without further local change before syncing. */
    debounce: number;
    /** Hours between full remote rescans (events keep things current in between). */
    fullScanHours: number;
    /** Where the session is stored: Secret Service ("keychain") or pass. */
    credentialsStore: 'keychain' | 'pass';
    stateDir?: string;
    trashDir?: string;
}

export const DEFAULTS: Omit<Settings, 'folders'> = {
    exclude: ['.git', 'node_modules'],
    maxDeletes: 50,
    debounce: 5,
    fullScanHours: 24,
    credentialsStore: 'keychain',
};

/** Keys that `config set` may change, with their parser. */
export const SETTABLE: Record<string, { help: string; parse: (v: string) => unknown }> = {
    debounce: { help: 'Sekunden Ruhe nach lokaler Änderung (1–3600)', parse: (v) => intIn(v, 1, 3600) },
    maxDeletes: { help: 'max. Löschungen pro Lauf und Ordner (≥ 1)', parse: (v) => intIn(v, 1, 1_000_000) },
    fullScanHours: { help: 'Stunden zwischen vollständigen Abgleichen (1–720)', parse: (v) => intIn(v, 1, 720) },
    exclude: { help: 'Ausnahmen, kommagetrennt (z. B. ".git,node_modules,*.tmp")', parse: (v) => splitList(v) },
    credentialsStore: {
        help: 'Speicher der Anmeldung: keychain | pass',
        parse: (v) => {
            if (v !== 'keychain' && v !== 'pass') {
                throw new Error('erlaubt: keychain, pass');
            }
            return v;
        },
    },
};

const DEFAULT_SEP = ',';

export function splitList(v: string): string[] {
    return v
        .split(DEFAULT_SEP)
        .map((s) => s.trim())
        .filter(Boolean);
}

function intIn(v: string, min: number, max: number): number {
    const n = Number(v);
    if (!Number.isInteger(n) || n < min || n > max) {
        throw new Error(`ganze Zahl zwischen ${min} und ${max} erwartet`);
    }
    return n;
}

export function defaultConfigPath(): string {
    return process.env.PDRIVE_SYNC_CONFIG || path.join(xdg('XDG_CONFIG_HOME', '.config'), 'pdrive-sync', 'config.json');
}

export function loadSettings(file: string): Settings {
    let raw: Partial<Settings> = {};
    if (existsSync(file)) {
        raw = JSON.parse(readFileSync(file, 'utf8')) as Partial<Settings>;
    }
    // null/missing values (e.g. from older configs) fall back to the defaults
    const defined = Object.fromEntries(Object.entries(raw).filter(([, v]) => v !== null && v !== undefined));
    const settings: Settings = { ...DEFAULTS, folders: [], ...defined } as Settings;
    if (settings.credentialsStore !== 'pass') {
        settings.credentialsStore = 'keychain';
    }
    settings.folders = (settings.folders || []).map((f) => ({
        name: f.name,
        local: f.local,
        remote: rjoin(f.remote || '/'),
        exclude: f.exclude || [],
    }));
    return settings;
}

/** Config generated by Home Manager (symlink into the read-only Nix store). */
export function isManaged(file: string): boolean {
    try {
        return lstatSync(file).isSymbolicLink() && realpathSync(file).startsWith('/nix/store/');
    } catch {
        return false;
    }
}

export function saveSettings(file: string, settings: Settings): void {
    if (isManaged(file)) {
        throw new Error(
            `${file} wird von Home Manager verwaltet – bitte in home.nix (services.pdrive-sync) ändern.`,
        );
    }
    mkdirSync(path.dirname(file), { recursive: true });
    const tmp = `${file}.tmp`;
    writeFileSync(tmp, JSON.stringify(settings, null, 2) + '\n');
    renameSync(tmp, file);
}

export function stateDirOf(settings: Settings): string {
    return settings.stateDir ? expandHome(settings.stateDir) : path.join(xdg('XDG_STATE_HOME', '.local/state'), 'pdrive-sync');
}

export function trashDirOf(settings: Settings): string {
    return settings.trashDir
        ? expandHome(settings.trashDir)
        : path.join(xdg('XDG_DATA_HOME', '.local/share'), 'pdrive-sync', 'trash');
}

/** Validation for a new/changed folder list; returns an error message or null. */
export function validateFolders(folders: FolderConfig[]): string | null {
    const names = new Set<string>();
    for (const f of folders) {
        if (!/^[\p{L}\p{N} ._-]+$/u.test(f.name)) {
            return `Ungültiger Name „${f.name}“ (erlaubt: Buchstaben, Ziffern, Leerzeichen, . _ -).`;
        }
        if (names.has(f.name)) {
            return `Der Name „${f.name}“ ist doppelt.`;
        }
        names.add(f.name);
        if (!f.local) {
            return `${f.name}: kein lokaler Ordner angegeben.`;
        }
    }
    const inside = (a: string, b: string) => {
        const x = a.replace(/\/+$/, '') + '/';
        const y = b.replace(/\/+$/, '') + '/';
        return x.startsWith(y) || y.startsWith(x);
    };
    for (let i = 0; i < folders.length; i++) {
        for (let j = i + 1; j < folders.length; j++) {
            const a = folders[i]!;
            const b = folders[j]!;
            if (inside(a.remote, b.remote)) {
                return `„${a.name}“ und „${b.name}“ überschneiden sich in Proton Drive.`;
            }
            if (inside(path.resolve(expandHome(a.local)), path.resolve(expandHome(b.local)))) {
                return `„${a.name}“ und „${b.name}“ überschneiden sich lokal.`;
            }
        }
    }
    return null;
}
